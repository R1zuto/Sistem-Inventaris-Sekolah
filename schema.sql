-- Skema Postgres (Neon) untuk Sistem Inventaris Sekolah
-- Jalankan SEKALI di Neon > SQL Editor.
CREATE TABLE users (
  id SERIAL PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL CHECK (role IN ('admin','guru')),
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE ruangan (
  id SERIAL PRIMARY KEY,
  nama_ruangan VARCHAR(100) NOT NULL UNIQUE,
  kategori VARCHAR(20) NOT NULL CHECK (kategori IN ('Kelas 7','Kelas 8','Kelas 9','Fasilitas','Kantor'))
);
CREATE TABLE inventaris (
  id SERIAL PRIMARY KEY,
  ruangan_id INT NOT NULL REFERENCES ruangan(id) ON DELETE CASCADE,
  nama_barang VARCHAR(100) NOT NULL,
  jumlah INT NOT NULL DEFAULT 1,
  kondisi VARCHAR(12) NOT NULL DEFAULT 'layak' CHECK (kondisi IN ('layak','tidak layak')),
  keterangan VARCHAR(255),
  updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE laporan_kerusakan (
  id SERIAL PRIMARY KEY,
  user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  inventaris_id INT NOT NULL REFERENCES inventaris(id) ON DELETE CASCADE,
  deskripsi TEXT NOT NULL,
  foto TEXT,
  status VARCHAR(10) NOT NULL DEFAULT 'Menunggu' CHECK (status IN ('Menunggu','Diproses','Selesai','Ditolak')),
  catatan_admin TEXT,
  tanggal_lapor TIMESTAMPTZ DEFAULT now()
);

